import { useEffect, useRef, useState, type Dispatch, type SetStateAction } from "react";
import { detectConcepts, generateAllConcepts, generateConceptViz, listConcepts, repairConceptViz } from "../../api/client";
import type { Concept, ConceptGeneration, ConceptsBackend, ConceptType } from "../../types";
import AnimView from "./AnimView";
import { mergePolled } from "./mergePolled";
import FormulaView from "./FormulaView";
import GraphView from "./GraphView";
import TextView from "./TextView";

const MAX_REPAIRS = 2;
const POLL_MS = 3000;
const GENERATE_ALL_KEY = "concepts.generateAll";

function readGenerateAll(): boolean {
  try { return localStorage.getItem(GENERATE_ALL_KEY) !== "0"; } catch { return true; }
}


const TYPE_BADGE: Record<ConceptType, { label: string; cls: string }> = {
  formula: { label: "formula", cls: "bg-violet-50 text-violet-700" },
  graph: { label: "graph", cls: "bg-sky-50 text-sky-700" },
  "2d-text": { label: "ref", cls: "bg-amber-50 text-amber-700" },
  "2d-anim": { label: "anim", cls: "bg-emerald-50 text-emerald-700" },
};

const BACKEND_LABEL: Record<ConceptsBackend, string> = {
  "claude-code": "Claude Opus (subscription)",
  api: "API · claude-sonnet-5-5",
};

interface Props {
  paperId: string;
  hasPdf: boolean;
  concepts: Concept[];
  backend: ConceptsBackend | null;
  onConceptsChange: Dispatch<SetStateAction<Concept[]>>;
  /** The background "generate all" job, if one was started for this paper. */
  generation: ConceptGeneration | null;
  onGenerationChange: (g: ConceptGeneration | null) => void;
  activeId: string | null;
  /** Select a concept (and show its page), or null to go back to the list. */
  onActivate: (concept: Concept | null) => void;
}

export default function ConceptsPanel({
  paperId, hasPdf, concepts, backend, onConceptsChange, generation, onGenerationChange, activeId, onActivate,
}: Props) {
  const [detecting, setDetecting] = useState(false);
  const [generateAll, setGenerateAll] = useState(readGenerateAll);
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [scanNote, setScanNote] = useState<string | null>(null);
  const repairs = useRef<Record<string, number>>({});

  const active = concepts.find((c) => c.id === activeId) ?? null;
  // A concept opened for the first time is generated by the effect below.
  const generating = !!active && !active.spec && !error;

  const replace = (updated: Concept) =>
    onConceptsChange((prev) => prev.map((c) => (c.id === updated.id ? updated : c)));

  async function runDetect() {
    if (concepts.length && !window.confirm("Replace the current concepts with a fresh scan?")) return;
    setDetecting(true);
    setError(null);
    onActivate(null);
    try {
      const res = await detectConcepts(paperId, generateAll);
      onConceptsChange(res.concepts);
      onGenerationChange(res.generation);
      repairs.current = {};
      setScanNote(
        res.pages_scanned < res.pages_total
          ? `Scanned the first ${res.pages_scanned} of ${res.pages_total} pages.`
          : null,
      );
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setDetecting(false);
    }
  }

  function toggleGenerateAll(on: boolean) {
    setGenerateAll(on);
    try { localStorage.setItem(GENERATE_ALL_KEY, on ? "1" : "0"); } catch { /* private mode */ }
  }

  async function startGenerateAll() {
    setError(null);
    try {
      const res = await generateAllConcepts(paperId);
      onConceptsChange((prev) => mergePolled(prev, res.concepts));
      onGenerationChange(res.generation);
    } catch (e) {
      setError((e as Error).message);
    }
  }

  // While the background job runs, pick up finished visualisations.
  const running = !!generation?.running;
  useEffect(() => {
    if (!running) return;
    let stopped = false;
    const timer = window.setInterval(() => {
      listConcepts(paperId)
        .then((r) => {
          if (stopped) return;
          onConceptsChange((prev) => mergePolled(prev, r.concepts));
          onGenerationChange(r.generation);
        })
        .catch(() => {});
    }, POLL_MS);
    return () => { stopped = true; window.clearInterval(timer); };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [running, paperId]);

  async function regenerate(concept: Concept) {
    setBusy("Regenerating…");
    setError(null);
    try {
      replace(await generateConceptViz(paperId, concept.id, true));
      repairs.current[concept.id] = 0;
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(null);
    }
  }

  async function onRuntimeError(concept: Concept, message: string) {
    const n = repairs.current[concept.id] ?? 0;
    if (n >= MAX_REPAIRS) {
      setError(`${message} — gave up after ${MAX_REPAIRS} repair attempts.`);
      return;
    }
    repairs.current[concept.id] = n + 1;
    setBusy(`Repairing (attempt ${n + 1} of ${MAX_REPAIRS})…`);
    setError(null);
    try {
      replace(await repairConceptViz(paperId, concept.id, message));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(null);
    }
  }

  // Generate lazily, the first time a concept is opened.
  useEffect(() => {
    if (!active || active.spec) return;
    let cancelled = false;
    generateConceptViz(paperId, active.id)
      .then((updated) => { if (!cancelled) { repairs.current[updated.id] = 0; replace(updated); } })
      .catch((e) => { if (!cancelled) setError((e as Error).message); });
    return () => { cancelled = true; };
    // Only when a different concept is opened, not when its spec arrives.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [activeId, paperId]);

  if (active) {
    const spec = active.spec;
    const tall = active.type === "graph" || active.type === "2d-anim";
    return (
      <div className="h-full flex flex-col gap-2">
        <div className="flex items-center gap-2 shrink-0">
          <button onClick={() => { setError(null); onActivate(null); }}
                  className="text-xs text-gray-500 hover:text-violet-600">← All concepts</button>
          <span className="ml-auto text-[10px] text-gray-400">p. {active.page + 1}</span>
          <button onClick={() => regenerate(active)} disabled={!!busy || generating}
                  className="text-[11px] px-2 py-0.5 rounded border border-gray-200 text-gray-500 hover:border-violet-300 hover:text-violet-600 disabled:opacity-40">
            Regenerate
          </button>
        </div>
        <div className="shrink-0">
          <p className="text-sm font-medium text-gray-800">{spec?.title || active.label}</p>
          {spec?.caption && <p className="text-xs text-gray-500">{spec.caption}</p>}
        </div>
        {(busy || generating) && <p className="text-xs text-violet-600 animate-pulse">{busy ?? "Generating…"}</p>}
        {error && <p className="text-xs rounded border border-rose-200 bg-rose-50 px-2 py-1 text-rose-700">{error}</p>}
        {spec && (
          <div className={`flex-1 min-h-0 overflow-y-auto ${tall ? "" : "pr-1"}`}>
            <div className={tall ? "h-full min-h-[260px]" : ""}>
              {spec.type === "formula" && <FormulaView spec={spec} />}
              {spec.type === "2d-text" && <TextView spec={spec} />}
              {spec.type === "graph" && <GraphView spec={spec} onRuntimeError={(m) => onRuntimeError(active, m)} />}
              {spec.type === "2d-anim" && <AnimView spec={spec} onRuntimeError={(m) => onRuntimeError(active, m)} />}
            </div>
          </div>
        )}
        <details className="shrink-0 text-[11px] text-gray-400">
          <summary className="cursor-pointer">Context sent to the model</summary>
          <p className="mt-1">{active.context}</p>
        </details>
      </div>
    );
  }

  const pages = [...new Set(concepts.map((c) => c.page))].sort((a, b) => a - b);
  const missing = concepts.filter((c) => !c.spec).length;

  return (
    <div className="h-full flex flex-col gap-2">
      <div className="flex items-center gap-2 shrink-0">
        <p className="text-xs text-gray-500">
          {concepts.length ? `${concepts.length} concepts on ${pages.length} pages` : "No concepts yet."}
        </p>
        <button onClick={runDetect} disabled={detecting || !hasPdf}
                className="ml-auto text-[11px] px-2 py-1 rounded bg-violet-600 text-white hover:bg-violet-700 disabled:opacity-40">
          {detecting ? "Scanning…" : concepts.length ? "Re-scan" : "Find concepts"}
        </button>
      </div>
      {hasPdf && (
        <label className="shrink-0 flex items-center gap-1.5 text-[11px] text-gray-500 cursor-pointer select-none">
          <input type="checkbox" checked={generateAll} onChange={(e) => toggleGenerateAll(e.target.checked)}
                 className="accent-violet-600" />
          Generate all visualisations after the scan
        </label>
      )}
      {running && generation && (
        <div className="shrink-0 space-y-1">
          <p className="text-xs text-violet-600">
            Generating visualisations: {generation.done} of {generation.total}
            {generation.failed > 0 && <span className="text-rose-600"> ({generation.failed} failed)</span>}
          </p>
          <div className="h-1 rounded bg-violet-100 overflow-hidden">
            <div className="h-full bg-violet-500 transition-all"
                 style={{ width: `${generation.total ? (100 * generation.done) / generation.total : 0}%` }} />
          </div>
        </div>
      )}
      {!running && !detecting && concepts.length > 0 && missing > 0 && (
        <button onClick={startGenerateAll}
                className="shrink-0 self-start text-[11px] px-2 py-0.5 rounded border border-violet-200 text-violet-700 hover:bg-violet-50">
          Generate all ({missing} missing)
        </button>
      )}
      {!hasPdf && <p className="text-xs text-gray-400">This paper has no PDF to scan.</p>}
      {detecting && (
        <p className="text-xs text-violet-600 animate-pulse">
          Reading the PDF page by page; this takes up to a minute or two for a long paper.
        </p>
      )}
      {error && <p className="text-xs rounded border border-rose-200 bg-rose-50 px-2 py-1 text-rose-700">{error}</p>}
      {scanNote && <p className="text-[11px] text-gray-400">{scanNote}</p>}

      <div className="flex-1 min-h-0 overflow-y-auto space-y-3">
        {pages.map((page) => (
          <div key={page}>
            <p className="text-[10px] uppercase tracking-wide text-gray-400 mb-1">Page {page + 1}</p>
            <div className="space-y-1">
              {concepts.filter((c) => c.page === page).map((c) => (
                <button key={c.id} onClick={() => { setError(null); onActivate(c); }}
                        className="w-full text-left flex items-center gap-2 rounded-lg border border-gray-100 px-2 py-1.5 hover:border-violet-300 hover:bg-violet-50/40">
                  <span className={`shrink-0 text-[10px] px-1.5 py-0.5 rounded ${TYPE_BADGE[c.type].cls}`}>
                    {TYPE_BADGE[c.type].label}
                  </span>
                  <span className="text-xs text-gray-700 truncate">{c.label}</span>
                  {c.spec && <span title="Visualisation ready" className="ml-auto shrink-0 w-1.5 h-1.5 rounded-full bg-emerald-500" />}
                  {!c.spec && c.spec_error && (
                    <span title={`Generation failed: ${c.spec_error}`} className="ml-auto shrink-0 w-1.5 h-1.5 rounded-full bg-rose-500" />
                  )}
                </button>
              ))}
            </div>
          </div>
        ))}
      </div>
      {backend && <p className="shrink-0 text-[10px] text-gray-400">Model: {BACKEND_LABEL[backend]}</p>}
    </div>
  );
}
